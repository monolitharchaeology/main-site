/* =============================================
   TRANSLATION ENGINE
   ============================================= */

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  // Swap text content on all marked elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.textContent = t[key];
    }
  });

  // Update the <html lang> attribute for accessibility & SEO
  document.documentElement.lang = lang;

  // Update active button state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Persist choice across page navigation
  localStorage.setItem('preferredLang', lang);

  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function initTranslations() {
  const saved = localStorage.getItem('preferredLang') || 'en';
  applyTranslations(saved);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      applyTranslations(btn.getAttribute('data-lang'));
    });
  });
}

document.addEventListener('DOMContentLoaded', initTranslations);
